-- Defects reported by the users.
--
-- The enums are stored as their names. The CHECK constraints list the allowed values, so a new
-- value of DefectPriority or DefectStatus needs a migration that replaces the constraint.
-- The title rule (5..120 characters after trimming) is enforced by the entity; the column only
-- bounds the length.

CREATE TABLE defects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(120)  NOT NULL,
    description         VARCHAR(2000),
    steps_to_reproduce  VARCHAR(5000),
    expected_result     VARCHAR(2000),
    actual_result       VARCHAR(2000),
    priority            VARCHAR(16)   NOT NULL DEFAULT 'MEDIUM',
    status              VARCHAR(16)   NOT NULL DEFAULT 'NEW',
    created_at          TIMESTAMPTZ   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    CONSTRAINT defects_priority_check CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT defects_status_check   CHECK (status IN ('NEW'))
);
