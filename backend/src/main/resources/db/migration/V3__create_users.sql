-- The users of the API and their roles.
--
-- The roles are a reference table rather than a CHECK constraint: users.role_code refers to it, so
-- a new role is an INSERT. The enum org.example.user.Role must list the same codes; a test
-- compares the two. What a role may do is decided by the application, not by this table.
--
-- Every user has exactly one role: the roles are nested (an ADMIN may do everything a MANAGER may),
-- so a user never needs two of them.

CREATE TABLE roles (
    code         VARCHAR(32)   PRIMARY KEY,
    description  VARCHAR(200)  NOT NULL
);

INSERT INTO roles (code, description) VALUES
    ('ADMIN',   'Creates, edits and reads the defects, manages the users'),
    ('MANAGER', 'Edits and reads the defects'),
    ('USER',    'Reads the defects');

-- The email is the login. It is stored normalized (stripped, lower case), so that "Qwe@Gmail.com"
-- and "qwe@gmail.com" are one account; the CHECK guards against a code path that forgets it.
-- The rules of a valid address are enforced by the application; the column only bounds the length
-- (254, the limit of RFC 5321 for a path).
--
-- password_hash holds the output of the DelegatingPasswordEncoder, e.g. "{bcrypt}$2a$12$..."
-- (68 characters): never the password itself.
--
-- A user is soft-deleted by setting deleted_at. The email is unique among the active users only,
-- so that the address of a deleted user may register again; the deleted row keeps its id, which
-- the history may refer to.
--
-- role_code has no default on purpose: the application always chooses the role explicitly.
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254)  NOT NULL,
    password_hash  VARCHAR(100)  NOT NULL,
    role_code      VARCHAR(32)   NOT NULL REFERENCES roles (code),
    deleted_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ   NOT NULL,
    updated_at     TIMESTAMPTZ   NOT NULL,
    CONSTRAINT users_email_lower_case_check CHECK (email = lower(email))
);

-- The application recognizes a duplicate registration by the name of this index.
CREATE UNIQUE INDEX users_email_active_key ON users (email) WHERE deleted_at IS NULL;
