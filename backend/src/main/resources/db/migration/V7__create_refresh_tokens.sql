-- The refresh tokens: they keep a user logged in beyond the short life of an access token.
--
-- The token itself (32 random bytes, sent to the browser in an HttpOnly cookie) is never stored,
-- only its SHA-256: whoever reads this table cannot use a token. A random value of 256 bits needs
-- no salt and no slow hash; the lookup by the hash is exact.
--
-- Every refresh replaces the token by a new one (rotation): the old row is revoked, the new one
-- joins the same family, i.e. the chain of tokens that started with one login. A revoked token
-- presented again means that two parties hold the chain (a stolen token), so the whole family is
-- revoked.
--
--   expires_at         the end of this token: the refresh time-to-live after its issue, but never
--                      after the end of its family
--   family_expires_at  the end of the family, fixed at the login: a chain refreshed forever would
--                      otherwise never require the password again
--   token_version      users.token_version when the token was issued: incrementing the column of
--                      the user (deletion, logout everywhere, later a new password) revokes the
--                      refresh tokens together with the access tokens, without touching this table
--   revoked_at         set by the rotation, a logout, a detected reuse
--
-- The users are soft-deleted, so a row never loses its user: no ON DELETE. The rows are not
-- cleaned up yet; an expired or revoked row is merely useless.

CREATE TABLE refresh_tokens (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES users (id),
    token_hash         BYTEA        NOT NULL,
    family_id          UUID         NOT NULL,
    token_version      INTEGER      NOT NULL,
    expires_at         TIMESTAMPTZ  NOT NULL,
    family_expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT refresh_tokens_token_hash_length_check CHECK (octet_length(token_hash) = 32),
    CONSTRAINT refresh_tokens_expiry_check CHECK (created_at < expires_at AND expires_at <= family_expires_at)
);

-- A refresh looks the token up by its hash; two equal hashes would mean two equal random tokens.
CREATE UNIQUE INDEX refresh_tokens_token_hash_key ON refresh_tokens (token_hash);
-- The revocation of a family (reuse, logout).
CREATE INDEX refresh_tokens_family_id_idx ON refresh_tokens (family_id);
-- The revocation of every live token of a user (logout everywhere).
CREATE INDEX refresh_tokens_user_id_live_idx ON refresh_tokens (user_id) WHERE revoked_at IS NULL;
